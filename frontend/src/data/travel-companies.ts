/**
 * Filter companies that serve a given destination city
 */
export function getCompaniesForDestination(destination: string): TravelCompany[] {
  const normalized = destination.trim();
  return EGYPT_TRAVEL_COMPANIES.filter(company =>
    company.destinations.some(d => d === normalized || d.includes(normalized) || normalized.includes(d))
  ).sort((a, b) => b.rating - a.rating);
}
